def main():
    assert len(NAMES)==256,len(NAMES)
    original=json.loads((ROOT/'analysis/fixed-catalog-original.json').read_text('utf8'))
    path=ROOT/'translations/fixed-catalog.ko.json';draft=json.loads(path.read_text('utf8'))
    for row in original:
        if row['category']!='item':continue
        icon=re.match(r'\{[^{}]+\}',row['source'])
        prefix=icon[0] if icon else '{pad}'
        draft[str(row['id'])]['translation']=prefix+NAMES[row['index']]
        draft[str(row['id'])]['status']='manual_context_checked'
    draft['673']['translation']='브라키오레이도스';draft['673']['status']='manual_context_checked'
    path.write_text(json.dumps(draft,ensure_ascii=False,indent=2)+'\n','utf8')
    print('Item names checked:',len(NAMES))

if __name__=='__main__':main()
