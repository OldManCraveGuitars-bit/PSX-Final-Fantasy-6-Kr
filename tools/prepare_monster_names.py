    path=ROOT/'translations/fixed-catalog.ko.json';rows=json.loads(path.read_text('utf8'));count=0
    for row in original:
        if row['category']!='monster' or not row['source']:continue
        target=rows[str(row['id'])]
        target['translation']=fixes.get(row['source'],target['translation'])
        target['status']='manual_context_checked';count+=1
    path.write_text(json.dumps(rows,ensure_ascii=False,indent=2)+'\n','utf8')
